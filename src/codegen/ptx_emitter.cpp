std::string PTXEmitter::ptx_target_arch() const {
    // Map the hardware target to a PTX .target architecture string.
    // We use the SM count and features as a heuristic.
    int64_t num_sms = target_.gpu.num_sms;
    bool has_tma = target_.has_tma;
    bool has_async = target_.has_async_copy;

    if (has_tma && num_sms >= 160) {
        return "sm_100";   // Blackwell B200
    }
    if (has_tma && num_sms >= 132) {
        return "sm_90";    // Hopper H100
    }
    if (has_async && num_sms >= 108) {
        return "sm_80";    // Ampere A100
    }
    if (has_async) {
        return "sm_75";    // Turing
    }
    return "sm_70";        // Volta
}

int64_t PTXEmitter::compute_smem_bytes(
    int64_t tile_m, int64_t tile_n, int64_t tile_k
) const {
    int64_t bpe = target_.bytes_per_element;
    // A tile: tile_m x tile_k elements
    // B tile: tile_k x tile_n elements
    // With double-buffering: 2 stages
    int64_t a_bytes = tile_m * tile_k * bpe;
    int64_t b_bytes = tile_k * tile_n * bpe;
    int64_t stages = target_.pipeline_stages;
    return (a_bytes + b_bytes) * stages;
}

void PTXEmitter::compute_launch_dims(
    int64_t M, int64_t N,
    int64_t tile_m, int64_t tile_n,
    int64_t& grid_x, int64_t& grid_y,
    int64_t& block_x, int64_t& block_y
) const {
    grid_x = (N + tile_n - 1) / tile_n;
    grid_y = (M + tile_m - 1) / tile_m;
    // One warp per CTA tile (conservative); can be scaled up.
    block_x = target_.gpu.warp_size;  // 32 threads per warp
    block_y = 1;
}

