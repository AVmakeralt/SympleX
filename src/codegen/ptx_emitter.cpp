std::string PTXEmitter::emit_matmul_kernel(
    int64_t M, int64_t N, int64_t K,
    const schedule::TileConfig& tile,
    const std::string& kernel_name
) const {
    std::ostringstream oss;

    int64_t tile_m = (tile.inner_tiles.size() > 0) ? tile.inner_tiles[0] : 128;
    int64_t tile_n = (tile.inner_tiles.size() > 1) ? tile.inner_tiles[1] : 128;
    int64_t tile_k = (tile.inner_tiles.size() > 2) ? tile.inner_tiles[2] : 32;

    // Header
    oss << emit_ptx_header(kernel_name);

    // Entry point declaration
    int64_t grid_x, grid_y, block_x, block_y;
    compute_launch_dims(M, N, tile_m, tile_n, grid_x, grid_y, block_x, block_y);

    oss << ".entry " << kernel_name << "(\n";
    oss << "    .param .u64 A_ptr,\n";
    oss << "    .param .u64 B_ptr,\n";
    oss << "    .param .u64 C_ptr,\n";
    oss << "    .param .u64 dim_M,\n";
    oss << "    .param .u64 dim_N,\n";
    oss << "    .param .u64 dim_K\n";
    oss << ")\n{\n";

    // Shared memory
    oss << emit_ptx_shared_mem_decl(tile_m, tile_n, tile_k);

    // Register declarations
    oss << "    // ---- Register declarations ----\n";
    oss << "    .reg .u64 %rd_ctaid_x, %rd_ctaid_y;\n";
    oss << "    .reg .u64 %rd_tid_x;\n";
    oss << "    .reg .u64 %rd_warp_id, %rd_lane_id;\n";
    oss << "    .reg .u64 %rd_a_ptr, %rd_b_ptr, %rd_c_ptr;\n";
    oss << "    .reg .u64 %rd_M, %rd_N, %rd_K;\n";
    oss << "    .reg .u64 %rd_row_base, %rd_col_base;\n";
    oss << "    .reg .u64 %rd_k_iter, %rd_k_offset;\n";
    oss << "    .reg .u64 %rd_smem_A, %rd_smem_B;\n";
    oss << "    .reg .u64 %rd_smem_A_stage, %rd_smem_B_stage;\n";
    oss << "    .reg .u64 %rd_stage;\n";
    oss << "    .reg .u64 %rd_c_gmem;\n";

    if (target_.has_tma) {
        oss << "    .reg .u64 %rd_a_tma_desc, %rd_b_tma_desc;\n";
        oss << "    .reg .u64 %rd_barrier;\n";
        oss << "    .reg .u32 %r_expect;\n";
    }

    oss << "    .reg .pred %p_k_loop, %p_m_bound, %p_n_bound, %p_in_bounds;\n";

    // C accumulator registers
    int64_t rep_m = tile_m / wmma_gen_.config().m;
    int64_t rep_n = tile_n / wmma_gen_.config().n;
    for (int64_t rm = 0; rm < rep_m; ++rm) {
        for (int64_t rn = 0; rn < rep_n; ++rn) {
            for (int i = 0; i < 4; ++i) {
                oss << "    .reg .f32 %R_c" << rm << "_" << rn << "_" << i << ";\n";
            }
        }
    }
    oss << "\n";

    // Prologue
    oss << emit_ptx_prologue();

    // Tiling loop (compute)
    oss << emit_ptx_tiling_loop(M, N, K, tile);

    // Epilogue — WMMA store C is placed AFTER the tiling loop so
    // that we store the computed result, not zeros.  The store code
    // is passed into the epilogue so it sits inside the in-bounds
    // guard (between the boundary check and EPILOGUE_SKIP).
    std::string c_store_code =
        wmma_gen_.emit_wmma_store_c(tile_m, tile_n, "%rd_c_gmem", N);
    oss << emit_ptx_epilogue(c_store_code);

    oss << "}\n";
    return oss.str();
}

