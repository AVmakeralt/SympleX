std::string PTXEmitter::emit_ptx_header(const std::string& kernel_name) const {
    std::ostringstream oss;
    oss << "// PTX kernel: " << kernel_name << "\n";
    oss << "// Generated by SympleX Polyhedral Tensor Superoptimizer\n";
    oss << ".version 8.5\n";
    oss << ".target " << ptx_target_arch() << "\n";
    oss << ".address_size 64\n\n";
    return oss.str();
}

std::string PTXEmitter::emit_ptx_param_decls(
    int64_t M, int64_t N, int64_t K
) const {
    std::ostringstream oss;
    oss << "// ---- Kernel parameters ----\n";
    oss << ".param .u64 " << "__param_A_ptr\n";
    oss << ".param .u64 " << "__param_B_ptr\n";
    oss << ".param .u64 " << "__param_C_ptr\n";
    oss << ".param .u64 " << "__param_M\n";
    oss << ".param .u64 " << "__param_N\n";
    oss << ".param .u64 " << "__param_K\n";
    oss << "\n";
    return oss.str();
}

std::string PTXEmitter::emit_ptx_shared_mem_decl(
    int64_t tile_m, int64_t tile_n, int64_t tile_k
) const {
    std::ostringstream oss;
    int64_t bpe = target_.bytes_per_element;
    int64_t stages = target_.pipeline_stages;

    // Shared memory for A tiles (pipeline_stages * tile_m * tile_k * bpe)
    int64_t smem_a_bytes = stages * tile_m * tile_k * bpe;
    // Shared memory for B tiles (pipeline_stages * tile_k * tile_n * bpe)
    int64_t smem_b_bytes = stages * tile_k * tile_n * bpe;

    oss << "// ---- Shared memory ----\n";
    oss << ".shared .align " << target_.memory_alignment << " .b8 smem_A["
        << smem_a_bytes << "];\n";
    oss << ".shared .align " << target_.memory_alignment << " .b8 smem_B["
        << smem_b_bytes << "];\n";
    oss << "\n";
    return oss.str();
}

std::string PTXEmitter::emit_ptx_prologue() const {
    std::ostringstream oss;

    oss << "    // ---- Prologue ----\n";
    oss << "    // Load kernel parameters\n";
    oss << "    ld.param.u64 %rd_a_ptr, [__param_A_ptr];\n";
    oss << "    ld.param.u64 %rd_b_ptr, [__param_B_ptr];\n";
    oss << "    ld.param.u64 %rd_c_ptr, [__param_C_ptr];\n";
    oss << "    ld.param.u64 %rd_M,     [__param_M];\n";
    oss << "    ld.param.u64 %rd_N,     [__param_N];\n";
    oss << "    ld.param.u64 %rd_K,     [__param_K];\n";
    oss << "\n";

    oss << "    // Compute CTA (block) and thread indices\n";
    oss << "    mov.u64 %rd_ctaid_x, %ctaid.x;\n";
    oss << "    mov.u64 %rd_ctaid_y, %ctaid.y;\n";
    oss << "    mov.u64 %rd_tid_x,   %tid.x;\n";
    oss << "    mov.u64 %rd_warp_id, %tid.x;\n";
    oss << "    shr.u64 %rd_warp_id, %rd_warp_id, 5;  // warp_id = tid / 32\n";
    oss << "    and.b64  %rd_lane_id, %rd_tid_x, 31;  // lane_id = tid % 32\n";
    oss << "\n";

    // Compute global row/col offsets for this CTA
    oss << "    // Global row offset = blockIdx.y * tile_m\n";
    oss << "    // Global col offset = blockIdx.x * tile_n\n";
    oss << "    // (tile dimensions are folded into the loop below)\n";
    oss << "\n";

    // Shared memory base pointers
    oss << "    // Shared memory base addresses\n";
    oss << "    mov.u64 %rd_smem_A, smem_A;\n";
    oss << "    mov.u64 %rd_smem_B, smem_B;\n";
    oss << "\n";

    return oss.str();
}

std::string PTXEmitter::emit_ptx_tiling_loop(
    int64_t M, int64_t N, int64_t K,
    const schedule::TileConfig& tile
) const {
    std::ostringstream oss;

    // Extract tile dimensions
    int64_t tile_m = (tile.inner_tiles.size() > 0) ? tile.inner_tiles[0] : 128;
    int64_t tile_n = (tile.inner_tiles.size() > 1) ? tile.inner_tiles[1] : 128;
    int64_t tile_k = (tile.inner_tiles.size() > 2) ? tile.inner_tiles[2] : 32;

    int64_t stages = target_.pipeline_stages;
    int64_t bpe = target_.bytes_per_element;
    int64_t smem_a_stride = tile_k;  // A is M x K, row-major, stride=K
    int64_t smem_b_stride = tile_n;  // B is K x N, row-major, stride=N

    // Grid dimensions
    int64_t grid_x, grid_y, block_x, block_y;
    compute_launch_dims(M, N, tile_m, tile_n, grid_x, grid_y, block_x, block_y);

    oss << "    // ---- Tiling loop ----\n";
    oss << "    // Tile: " << tile_m << "x" << tile_n << "x" << tile_k << "\n";
    oss << "    // Pipeline stages: " << stages << "\n";
    oss << "    // Grid: " << grid_x << " x " << grid_y << "\n";
    oss << "    // Block: " << block_x << " x " << block_y << "\n";
    oss << "\n";

    // Compute global offsets for this CTA
    oss << "    // Compute base global pointers for this CTA\n";
    oss << "    // CTA row base = blockIdx.y * " << tile_m << "\n";
    oss << "    // CTA col base = blockIdx.x * " << tile_n << "\n";
    oss << "    mul.lo.u64 %rd_row_base, %rd_ctaid_y, " << tile_m << ";\n";
    oss << "    mul.lo.u64 %rd_col_base, %rd_ctaid_x, " << tile_n << ";\n";
    oss << "\n";

    // Initialise C accumulator to zero
    const auto& wcfg = wmma_gen_.config();
    int64_t rep_m = tile_m / wcfg.m;
    int64_t rep_n = tile_n / wcfg.n;

    oss << "    // Zero C accumulator registers\n";
    for (int64_t rm = 0; rm < rep_m; ++rm) {
        for (int64_t rn = 0; rn < rep_n; ++rn) {
            for (int i = 0; i < 4; ++i) {
                oss << "    mov.f32 %R_c" << rm << "_" << rn << "_" << i
                    << ", 0.0;\n";
            }
        }
    }
    oss << "\n";

    // K-loop
    int64_t k_iters = (K + tile_k - 1) / tile_k;
    oss << "    // K-loop: " << k_iters << " iterations\n";
    oss << "    mov.u64 %rd_k_iter, 0;\n";
    oss << "    mov.u64 %rd_k_offset, 0;\n";
    oss << "\n";

    oss << "K_LOOP:\n";

    // ── Async copy from global to shared memory ──
    if (target_.has_tma) {
        oss << "    // TMA copy: A tile from global to shared memory\n";
        oss << "    // cp.async.bulk.tensor.2d.shared.global.mbarrier::complete_tx::bytes\n";
        oss << "    //   smem_A[stage], [A_tensor_desc, row_base, k_offset], tile_m*"
            << tile_k << "*" << bpe << " bytes, barrier\n";
        oss << "    {\n";
        oss << "        .reg .u64 %tma_bytes_a;\n";
        oss << "        mov.u64 %tma_bytes_a, " << (tile_m * tile_k * bpe) << ";\n";
        oss << "        cp.async.bulk.tensor.2d.shared.global"
            << ".mbarrier::complete_tx::bytes"
            << " [%rd_smem_A_stage], [%rd_a_tma_desc, %rd_row_base, %rd_k_offset],"
            << " %tma_bytes_a, [%rd_barrier];\n";
        oss << "    }\n";
        oss << "\n";

        oss << "    // TMA copy: B tile from global to shared memory\n";
        oss << "    {\n";
        oss << "        .reg .u64 %tma_bytes_b;\n";
        oss << "        mov.u64 %tma_bytes_b, " << (tile_k * tile_n * bpe) << ";\n";
        oss << "        cp.async.bulk.tensor.2d.shared.global"
            << ".mbarrier::complete_tx::bytes"
            << " [%rd_smem_B_stage], [%rd_b_tma_desc, %rd_k_offset, %rd_col_base],"
            << " %tma_bytes_b, [%rd_barrier];\n";
        oss << "    }\n";
        oss << "\n";

        oss << "    // Wait for TMA copies to complete\n";
        oss << "    mbarrier.wait.shared.b64 [%rd_barrier], %r_expect;\n";
        oss << "\n";
    } else if (target_.has_async_copy) {
        // cp.async path (Ampere/Turing)
        oss << "    // Async copy A tile from global to shared (cp.async)\n";
        oss << "    // Each warp thread copies a strided subset of elements\n";
        oss << "    {\n";
        oss << "        .reg .u64 %src_a, %dst_a;\n";
        oss << "        .reg .u64 %cp_row, %cp_col;\n";
        oss << "        // Compute per-thread source/dest offsets\n";
        oss << "        mov.u64 %cp_row, %rd_lane_id;\n";
        oss << "        // src = A_ptr + (row_base + cp_row) * K + k_offset\n";
        oss << "        mad.lo.u64 %src_a, %cp_row, %rd_K, %rd_k_offset;\n";
        oss << "        mad.lo.u64 %src_a, %src_a, " << bpe << ", %rd_a_ptr;\n";
        oss << "        // dst = smem_A + cp_row * tile_k * bpe\n";
        oss << "        mad.lo.u64 %dst_a, %cp_row, " << (tile_k * bpe) << ", %rd_smem_A;\n";
        oss << "        cp.async.ca.shared.global [%dst_a], [%src_a], "
            << (tile_k * bpe) << ";\n";
        oss << "    }\n";
        oss << "\n";

        oss << "    // Async copy B tile from global to shared (cp.async)\n";
        oss << "    {\n";
        oss << "        .reg .u64 %src_b, %dst_b;\n";
        oss << "        .reg .u64 %cp_k_row, %cp_n_col;\n";
        oss << "        mov.u64 %cp_k_row, %rd_lane_id;\n";
        oss << "        mad.lo.u64 %src_b, %cp_k_row, %rd_N, %rd_col_base;\n";
        oss << "        mad.lo.u64 %src_b, %src_b, " << bpe << ", %rd_b_ptr;\n";
        oss << "        mad.lo.u64 %dst_b, %cp_k_row, " << (tile_n * bpe)
            << ", %rd_smem_B;\n";
        oss << "        cp.async.ca.shared.global [%dst_b], [%src_b], "
            << (tile_n * bpe) << ";\n";
        oss << "    }\n";
        oss << "\n";

        oss << "    // Commit and wait for async copies\n";
        oss << "    cp.async.commit_group;\n";
        oss << "    cp.async.wait_group 0;\n";
        oss << "\n";
    } else {
        // Synchronous copy (Volta and older)
        oss << "    // Synchronous load A tile to shared memory\n";
        oss << "    // Each thread loads one element at a time\n";
        oss << "    {\n";
        oss << "        .reg .u64 %ld_offset_a;\n";
        oss << "        .reg ." << (bpe == 2 ? "f16" : "f32") << " %ld_val_a;\n";
        oss << "        mov.u64 %ld_offset_a, %rd_lane_id;\n";
        oss << "        // For each row assigned to this thread\n";
        oss << "        ld.global." << (bpe == 2 ? "f16" : "f32")
            << " %ld_val_a, [%rd_a_ptr + %ld_offset_a];\n";
        oss << "        st.shared." << (bpe == 2 ? "f16" : "f32")
            << " [%rd_smem_A + %ld_offset_a], %ld_val_a;\n";
        oss << "    }\n";
        oss << "\n";

        oss << "    // Synchronous load B tile to shared memory\n";
        oss << "    {\n";
        oss << "        .reg .u64 %ld_offset_b;\n";
        oss << "        .reg ." << (bpe == 2 ? "f16" : "f32") << " %ld_val_b;\n";
        oss << "        mov.u64 %ld_offset_b, %rd_lane_id;\n";
        oss << "        ld.global." << (bpe == 2 ? "f16" : "f32")
            << " %ld_val_b, [%rd_b_ptr + %ld_offset_b];\n";
        oss << "        st.shared." << (bpe == 2 ? "f16" : "f32")
            << " [%rd_smem_B + %ld_offset_b], %ld_val_b;\n";
        oss << "    }\n";
        oss << "\n";

        oss << "    bar.sync 0;\n";
        oss << "\n";
    }

    // ── Swizzle before WMMA load ──
    oss << swizzle_gen_.emit_smem_unswizzle(tile_m, tile_k, smem_a_stride);
    oss << "\n";

    // ── WMMA load A from shared memory ──
    oss << wmma_gen_.emit_wmma_load_a(tile_m, tile_k, "%rd_smem_A", smem_a_stride);
    oss << "\n";

    // ── WMMA load B from shared memory ──
    oss << swizzle_gen_.emit_smem_unswizzle(tile_k, tile_n, smem_b_stride);
    oss << "\n";
    oss << wmma_gen_.emit_wmma_load_b(tile_k, tile_n, "%rd_smem_B", smem_b_stride);
    oss << "\n";

    // ── WMMA compute ──
    oss << wmma_gen_.emit_wmma_mma(tile_m, tile_n, tile_k);
    oss << "\n";

    // ── Advance K offset ──
    oss << "    // Advance K offset\n";
    oss << "    add.u64 %rd_k_offset, %rd_k_offset, " << tile_k << ";\n";
    oss << "    add.u64 %rd_k_iter, %rd_k_iter, 1;\n";

    // ── Double-buffer swap ──
    if (stages >= 2) {
        oss << "    // Double-buffer: swap shared memory stage pointers\n";
        oss << "    // stage ^= 1\n";
        oss << "    xor.b64 %rd_stage, %rd_stage, 1;\n";
        oss << "    mov.u64 %rd_smem_A_stage, %rd_smem_A;\n";
        oss << "    mov.u64 %rd_smem_B_stage, %rd_smem_B;\n";
        oss << "    mad.lo.u64 %rd_smem_A_stage, %rd_stage, "
            << (tile_m * tile_k * bpe) << ", %rd_smem_A;\n";
        oss << "    mad.lo.u64 %rd_smem_B_stage, %rd_stage, "
            << (tile_k * tile_n * bpe) << ", %rd_smem_B;\n";
    }

    oss << "\n";

    // ── Loop condition ──
    oss << "    // Loop condition: k_iter < " << k_iters << "\n";
    oss << "    setp.lt.u64 %p_k_loop, %rd_k_iter, " << k_iters << ";\n";
    oss << "    @%p_k_loop bra K_LOOP;\n";
    oss << "\n";

    // ── Barrier after K-loop ──
    oss << "    bar.sync 0;\n";
    oss << "\n";

    return oss.str();
}

std::string PTXEmitter::emit_ptx_epilogue(
    const std::string& c_store_code
) const {
    std::ostringstream oss;
    oss << "    // ---- Epilogue ----\n";
    oss << "    // Store C accumulator to global memory\n";
    oss << "\n";

    // Apply swizzle on the way out (if needed for shared memory write-back)
    oss << swizzle_gen_.emit_smem_swizzle(1, 1, 1);
    oss << "\n";

    oss << "    // Compute global C pointer for this CTA\n";
    oss << "    // C_ptr += row_base * N + col_base\n";
    oss << "    mad.lo.u64 %rd_c_gmem, %rd_row_base, %rd_N, %rd_col_base;\n";
    oss << "    mad.lo.u64 %rd_c_gmem, %rd_c_gmem, " << target_.bytes_per_element
        << ", %rd_c_ptr;\n";
    oss << "\n";

    oss << "    // Boundary check: skip store if out of bounds\n";
    oss << "    setp.lt.u64 %p_m_bound, %rd_row_base, %rd_M;\n";
    oss << "    setp.lt.u64 %p_n_bound, %rd_col_base, %rd_N;\n";
    oss << "    and.pred  %p_in_bounds, %p_m_bound, %p_n_bound;\n";
    oss << "    @!%p_in_bounds bra EPILOGUE_SKIP;\n";
    oss << "\n";

    // C-store instructions: only reached when the thread IS in bounds.
    // Previously this code was emitted before the tiling loop (storing
    // zeros) or the branch jumped unconditionally past it.  Both bugs
    // are fixed here: the store is now AFTER compute and inside the
    // in-bounds path.
    oss << c_store_code;
    oss << "\n";

    oss << "EPILOGUE_SKIP:\n";
    oss << "    // Kernel exit\n";
    oss << "    ret;\n";
    oss << "\n";
    return oss.str();
}

