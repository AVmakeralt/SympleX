std::string PTXEmitter::emit_conv2d_param_decls(
    int64_t batch, int64_t oc, int64_t ic,
    int64_t oh, int64_t ow, int64_t kh, int64_t kw,
    int64_t stride, int64_t pad
) const {
    std::ostringstream oss;
    oss << "    .param .u64 input_ptr,\n";
    oss << "    .param .u64 kernel_ptr,\n";
    oss << "    .param .u64 output_ptr,\n";
    oss << "    .param .u64 dim_batch,\n";
    oss << "    .param .u64 dim_oc,\n";
    oss << "    .param .u64 dim_ic,\n";
    oss << "    .param .u64 dim_oh,\n";
    oss << "    .param .u64 dim_ow,\n";
    oss << "    .param .u64 dim_kh,\n";
    oss << "    .param .u64 dim_kw,\n";
    oss << "    .param .u64 dim_stride,\n";
    oss << "    .param .u64 dim_pad\n";
    return oss.str();
}

std::string PTXEmitter::emit_conv2d_tiling_loop(
    int64_t batch, int64_t oc, int64_t ic,
    int64_t oh, int64_t ow, int64_t kh, int64_t kw,
    int64_t stride, int64_t pad,
    const schedule::TileConfig& tile
) const {
    std::ostringstream oss;
    int64_t bpe = target_.bytes_per_element;

    // Conv2d is lowered to an im2col GEMM:
    //   output[batch*oc*oh*ow] = im2col(input) * kernel[oc*ic*kh*kw]
    // The im2col matrix has dimensions (batch*oh*ow) x (ic*kh*kw)
    // The kernel matrix has dimensions (ic*kh*kw) x oc
    // So the effective GEMM is:
    //   M = batch * oh * ow
    //   N = oc
    //   K = ic * kh * kw

    int64_t eff_M = batch * oh * ow;
    int64_t eff_N = oc;
    int64_t eff_K = ic * kh * kw;

    int64_t tile_m = (tile.inner_tiles.size() > 0) ? tile.inner_tiles[0] : 128;
    int64_t tile_n = (tile.inner_tiles.size() > 1) ? tile.inner_tiles[1] : 128;
    int64_t tile_k = (tile.inner_tiles.size() > 2) ? tile.inner_tiles[2] : 32;

    // Align tile_k to kh*kw for clean im2col rows
    int64_t kw_kh = kh * kw;
    if (kw_kh > 0 && tile_k % kw_kh != 0) {
        tile_k = ((tile_k + kw_kh - 1) / kw_kh) * kw_kh;
    }

    oss << "    // Conv2d lowered to im2col GEMM:\n";
    oss << "    //   M = batch*oh*ow = " << eff_M << "\n";
    oss << "    //   N = oc = " << eff_N << "\n";
    oss << "    //   K = ic*kh*kw = " << eff_K << "\n";
    oss << "    // Tile: " << tile_m << "x" << tile_n << "x" << tile_k << "\n";
    oss << "\n";

    // K-loop for the im2col GEMM
    int64_t k_iters = (eff_K + tile_k - 1) / tile_k;
    oss << "    mov.u64 %rd_k_iter, 0;\n";
    oss << "    mov.u64 %rd_k_offset, 0;\n";
    oss << "\n";

    oss << "CONV2D_K_LOOP:\n";

    // For conv2d, the A "matrix" is the im2col expansion of the input tensor.
    // Each row (batch_idx, oh_idx, ow_idx) generates ic*kh*kw elements by
    // gathering from input[batch, ic, oh*s+kh-pad, ow*s+kw-pad].
    // We emit the gather pattern inline.

    oss << "    // ---- Im2col gather: load input tile to shared memory ----\n";
    oss << "    // For each output pixel in the tile, gather from input\n";
    oss << "    // using stride=" << stride << ", pad=" << pad << "\n";
    oss << "    {\n";
    oss << "        .reg .u64 %im_row, %im_col, %im_batch;\n";
    oss << "        .reg .u64 %im_ih, %im_iw;\n";
    oss << "        .reg .u64 %im_ic, %im_kh, %im_kw;\n";
    oss << "        .reg .u64 %im_src_offset;\n";
    oss << "        .reg ." << (bpe == 2 ? "f16" : "f32") << " %im_val;\n";
    oss << "        .reg .pred %im_pad_pred;\n";
    oss << "\n";

    oss << "        // Thread %lane_id gathers one element\n";
    oss << "        // Decompose linear index into (batch, oh, ow, ic, kh, kw)\n";
    oss << "        // using the k_offset to determine the ic/kh/kw coordinates\n";
    oss << "        mov.u64 %im_kh, %rd_k_offset;\n";
    oss << "        div.u64 %im_ic, %im_kh, " << kw_kh << ";\n";
    oss << "        rem.u64 %im_kh, %im_kh, " << kw_kh << ";\n";
    oss << "        div.u64 %im_kw, %im_kh, " << kw << ";\n";
    oss << "        rem.u64 %im_kw, %im_kh, " << kw << ";\n";
    oss << "        // Actually im_kh is now the remainder, re-derive:\n";
    oss << "        mov.u64 %im_kh_row, %im_kh;\n";
    oss << "        div.u64 %im_kh, %im_kh_row, " << kw << ";\n";
    oss << "        rem.u64 %im_kw, %im_kh_row, " << kw << ";\n";
    oss << "\n";

    oss << "        // Compute input spatial coordinates\n";
    oss << "        // ih = oh * stride + kh - pad\n";
    oss << "        // iw = ow * stride + kw - pad\n";
    oss << "        mad.lo.u64 %im_ih, %rd_oh, " << stride << ", %im_kh;\n";
    oss << "        sub.u64 %im_ih, %im_ih, " << pad << ";\n";
    oss << "        mad.lo.u64 %im_iw, %rd_ow, " << stride << ", %im_kw;\n";
    oss << "        sub.u64 %im_iw, %im_iw, " << pad << ";\n";
    oss << "\n";

    oss << "        // Check if within input bounds (not padding)\n";
    oss << "        setp.ge.u64 %im_pad_pred, %im_ih, 0;\n";
    oss << "        setp.lt.u64 %im_pad_pred, %im_ih, " << (oh * stride + kh) << ";\n";
    oss << "        // Load if not in padding region\n";
    oss << "        @%im_pad_pred ld.global." << (bpe == 2 ? "f16" : "f32")
        << " %im_val, [%rd_input_ptr + %im_src_offset];\n";
    oss << "        @!%im_pad_pred mov." << (bpe == 2 ? "f16" : "f32")
        << " %im_val, 0;\n";
    oss << "        st.shared." << (bpe == 2 ? "f16" : "f32")
        << " [%rd_smem_A + %rd_lane_id], %im_val;\n";
    oss << "    }\n";
    oss << "\n";

    // Load kernel tile (similar to B in GEMM)
    oss << "    // Load kernel tile to shared memory\n";
    oss << "    // Kernel is stored as [oc, ic, kh, kw], so the B tile\n";
    oss << "    // for this K slice starts at kernel_ptr + k_offset * oc\n";
    if (target_.has_async_copy) {
        oss << "    cp.async.ca.shared.global [%rd_smem_B], [%rd_kernel_ptr + %rd_k_offset_b], "
            << (tile_n * tile_k * bpe / target_.gpu.warp_size) << ";\n";
        oss << "    cp.async.commit_group;\n";
        oss << "    cp.async.wait_group 0;\n";
    } else {
        oss << "    ld.global." << (bpe == 2 ? "f16" : "f32")
            << " %conv_b_val, [%rd_kernel_ptr + %rd_lane_id];\n";
        oss << "    st.shared." << (bpe == 2 ? "f16" : "f32")
            << " [%rd_smem_B + %rd_lane_id], %conv_b_val;\n";
    }
    oss << "\n";

    oss << "    bar.sync 0;\n";
    oss << "\n";

    // WMMA on the gathered tiles
    oss << wmma_gen_.emit_wmma_load_a(tile_m, tile_k, "%rd_smem_A", tile_k);
    oss << wmma_gen_.emit_wmma_load_b(tile_k, tile_n, "%rd_smem_B", tile_n);
    oss << wmma_gen_.emit_wmma_mma(tile_m, tile_n, tile_k);
    oss << "\n";

    // Advance K
    oss << "    add.u64 %rd_k_offset, %rd_k_offset, " << tile_k << ";\n";
    oss << "    add.u64 %rd_k_iter, %rd_k_iter, 1;\n";
    oss << "    setp.lt.u64 %p_k_loop, %rd_k_iter, " << k_iters << ";\n";
    oss << "    @%p_k_loop bra CONV2D_K_LOOP;\n";
    oss << "\n";

    return oss.str();
}

// ---------------------------------------------------------------------------
// Complete conv2d kernel
// ---------------------------------------------------------------------------

std::string PTXEmitter::emit_conv2d_kernel(
    int64_t batch, int64_t oc, int64_t ic,
    int64_t oh, int64_t ow, int64_t kh, int64_t kw,
    int64_t stride, int64_t pad,
    const schedule::TileConfig& tile,
    const std::string& kernel_name
) const {
    std::ostringstream oss;

    int64_t tile_m = (tile.inner_tiles.size() > 0) ? tile.inner_tiles[0] : 128;
    int64_t tile_n = (tile.inner_tiles.size() > 1) ? tile.inner_tiles[1] : 128;
    int64_t tile_k = (tile.inner_tiles.size() > 2) ? tile.inner_tiles[2] : 32;
    int64_t bpe = target_.bytes_per_element;

    // Header
    oss << emit_ptx_header(kernel_name);

    // Entry point
    oss << ".entry " << kernel_name << "(\n";
    oss << emit_conv2d_param_decls(batch, oc, ic, oh, ow, kh, kw, stride, pad);
    oss << ")\n{\n";

    // Shared memory
    oss << emit_ptx_shared_mem_decl(tile_m, tile_n, tile_k);

    // Register declarations
    oss << "    // ---- Register declarations ----\n";
    oss << "    .reg .u64 %rd_ctaid_x, %rd_ctaid_y, %rd_ctaid_z;\n";
    oss << "    .reg .u64 %rd_tid_x;\n";
    oss << "    .reg .u64 %rd_warp_id, %rd_lane_id;\n";
    oss << "    .reg .u64 %rd_input_ptr, %rd_kernel_ptr, %rd_output_ptr;\n";
    oss << "    .reg .u64 %rd_batch, %rd_oc, %rd_ic;\n";
    oss << "    .reg .u64 %rd_oh, %rd_ow, %rd_kh, %rd_kw;\n";
    oss << "    .reg .u64 %rd_stride, %rd_pad;\n";
    oss << "    .reg .u64 %rd_row_base, %rd_col_base;\n";
    oss << "    .reg .u64 %rd_k_iter, %rd_k_offset;\n";
    oss << "    .reg .u64 %rd_smem_A, %rd_smem_B;\n";
    oss << "    .reg .u64 %rd_out_gmem;\n";
    oss << "    .reg .pred %p_k_loop, %p_in_bounds;\n";
    oss << "    .reg ." << (bpe == 2 ? "f16" : "f32") << " %conv_b_val;\n";

    // C accumulator registers
    int64_t rep_m = tile_m / wmma_gen_.config().m;
    int64_t rep_n = tile_n / wmma_gen_.config().n;
    for (int64_t rm = 0; rm < rep_m; ++rm) {
        for (int64_t rn = 0; rn < rep_n; ++rn) {
            for (int i = 0; i < 4; ++i) {
                oss << "    .reg .f32 %R_c" << rm << "_" << rn << "_" << i << ";\n";
            }
        }
    }
    oss << "\n";

    // Prologue: load parameters
    oss << "    // ---- Conv2d Prologue ----\n";
    oss << "    ld.param.u64 %rd_input_ptr,  [input_ptr];\n";
    oss << "    ld.param.u64 %rd_kernel_ptr, [kernel_ptr];\n";
    oss << "    ld.param.u64 %rd_output_ptr, [output_ptr];\n";
    oss << "    ld.param.u64 %rd_batch, [dim_batch];\n";
    oss << "    ld.param.u64 %rd_oc,     [dim_oc];\n";
    oss << "    ld.param.u64 %rd_ic,     [dim_ic];\n";
    oss << "    ld.param.u64 %rd_oh,     [dim_oh];\n";
    oss << "    ld.param.u64 %rd_ow,     [dim_ow];\n";
    oss << "    ld.param.u64 %rd_kh,     [dim_kh];\n";
    oss << "    ld.param.u64 %rd_kw,     [dim_kw];\n";
    oss << "    ld.param.u64 %rd_stride, [dim_stride];\n";
    oss << "    ld.param.u64 %rd_pad,    [dim_pad];\n";
    oss << "\n";

    oss << "    // Compute CTA indices\n";
    oss << "    mov.u64 %rd_ctaid_x, %ctaid.x;\n";
    oss << "    mov.u64 %rd_ctaid_y, %ctaid.y;\n";
    oss << "    mov.u64 %rd_ctaid_z, %ctaid.z;\n";
    oss << "    mov.u64 %rd_tid_x,   %tid.x;\n";
    oss << "    mov.u64 %rd_warp_id, %rd_tid_x;\n";
    oss << "    shr.u64 %rd_warp_id, %rd_warp_id, 5;\n";
    oss << "    and.b64 %rd_lane_id, %rd_tid_x, 31;\n";
    oss << "\n";

    // Shared memory base pointers
    oss << "    mov.u64 %rd_smem_A, smem_A;\n";
    oss << "    mov.u64 %rd_smem_B, smem_B;\n";
    oss << "\n";

    // Zero C accumulators
    oss << "    // Zero C accumulators\n";
    for (int64_t rm = 0; rm < rep_m; ++rm) {
        for (int64_t rn = 0; rn < rep_n; ++rn) {
            for (int i = 0; i < 4; ++i) {
                oss << "    mov.f32 %R_c" << rm << "_" << rn << "_" << i
                    << ", 0.0;\n";
            }
        }
    }
    oss << "\n";

    // Conv2d tiling loop (im2col GEMM)
    oss << emit_conv2d_tiling_loop(
        batch, oc, ic, oh, ow, kh, kw, stride, pad, tile);

    // Store output
    oss << "    // Store output to global memory\n";
    oss << wmma_gen_.emit_wmma_store_c(tile_m, tile_n, "%rd_output_ptr", oc * oh * ow);

    // Epilogue
    oss << "    bar.sync 0;\n";
    oss << "    ret;\n";
    oss << "}\n";

    return oss.str();
}

